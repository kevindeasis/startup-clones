import PDFDocument from "pdfkit";
import type { Destination } from "./destinations";
import { nationalityName } from "./destinations";
import type { ApplicationRow, TravellerRow } from "./schema";
import { DISCLAIMER, type PassportKey } from "./types";

const LABELS: Record<PassportKey, string> = {
  surname: "Surname (family name)",
  givenNames: "First name(s)",
  passportNumber: "Travel document number",
  nationality: "Nationality (as in passport)",
  dateOfBirth: "Date of birth",
  sex: "Sex",
  issueDate: "Date of issue",
  expiryDate: "Valid until",
  issuingAuthority: "Issued by",
  mrzLine1: "MRZ line 1",
  mrzLine2: "MRZ line 2",
};

const TITLES = {
  schengen: "Schengen Short-Stay Visa - Pre-filled Application Summary",
  uk: "UK Standard Visitor - Pre-filled Application Summary",
  us: "US B1/B2 (DS-160 style) - Pre-filled Application Summary",
} as const;

export function buildFormPdf(app: ApplicationRow, dest: Destination, t: TravellerRow): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "A4", margin: 48, info: { Title: TITLES[dest.formStyle] } });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const p = t.passport;
    const section = (title: string) => {
      doc.moveDown(0.8).font("Helvetica-Bold").fontSize(12).fillColor("#3730a3").text(title);
      doc.moveTo(doc.x, doc.y + 2).lineTo(547, doc.y + 2).strokeColor("#c7d2fe").stroke();
      doc.moveDown(0.5).fillColor("#111827");
    };
    const field = (label: string, value: string | number | null | undefined) => {
      const y = doc.y;
      doc.font("Helvetica").fontSize(9).fillColor("#6b7280").text(label, 48, y, { width: 190 });
      doc.font("Helvetica-Bold").fontSize(10).fillColor("#111827").text(String(value ?? "-") || "-", 245, y, { width: 300 });
      doc.moveDown(0.35);
    };

    doc.font("Helvetica-Bold").fontSize(16).fillColor("#111827").text(TITLES[dest.formStyle]);
    doc.font("Helvetica").fontSize(9).fillColor("#6b7280")
      .text("Generated by Visa Copilot (demo clone). Our own layout - not an official government form. Check every field before use.");

    section("1. Applicant (from passport)");
    field("Surname", p.surname);
    field("Given names", p.givenNames);
    field("Date of birth", p.dateOfBirth);
    field("Sex", p.sex);
    field("Nationality", `${p.nationality ?? "-"} (${nationalityName(app.nationality)})`);

    section("2. Travel document");
    field("Document number", p.passportNumber);
    field("Date of issue", p.issueDate);
    field("Valid until", p.expiryDate);
    field("Issued by", p.issuingAuthority);
    if (dest.formStyle === "us") {
      field(LABELS.mrzLine1, p.mrzLine1);
      field(LABELS.mrzLine2, p.mrzLine2);
    }

    section("3. Trip details");
    field("Destination", `${dest.name} - ${dest.visaType}`);
    field("Purpose of travel", app.purpose);
    field("Planned departure", app.departureDate);
    field("Planned return", app.returnDate);
    field("Travellers in application", `${t.index} of ${app.travellerCount}`);
    if (dest.formStyle === "schengen") {
      field("Number of entries requested", "Single (to be confirmed)");
      field("Member state of main destination", dest.name);
    } else if (dest.formStyle === "uk") {
      field("Visit type", "Standard Visitor - tourism");
      field("Funds available for trip", "To be completed by applicant (see bank statement)");
    } else {
      field("Visa class", "B1/B2 - tourism / visitor");
      field("Who is paying for the trip", "Self (to be confirmed)");
    }

    section("4. Declarations (to be completed by the applicant)");
    doc.font("Helvetica").fontSize(9).fillColor("#374151")
      .text("Address, occupation, employer and family details are not collected by this demo. Complete them on the official channel.");

    doc.moveDown(2).font("Helvetica-Oblique").fontSize(8).fillColor("#6b7280")
      .text(`${dest.note} ${DISCLAIMER} Application ${app.id}.`);
    doc.end();
  });
}
