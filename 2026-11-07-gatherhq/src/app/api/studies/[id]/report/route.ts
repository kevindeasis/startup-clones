import { getInterviews, getQuestions, latestModel } from "@/lib/db";
import { studyOr404 } from "@/lib/api";

export const dynamic = "force-dynamic";

export async function GET(_: Request, { params }: { params: Promise<{ id: string }> }) {
  const { id } = await params;
  const r = studyOr404(id);
  if (r.res) return r.res;
  const s = r.study;
  const ivs = getInterviews(id);
  const m = latestModel(id)?.model;
  const L: string[] = [];
  L.push(`# ${s.title}`, "", `**Goal:** ${s.goal}`, "", `**Audience:** ${s.audience}`, "",
    `**Interviews:** ${ivs.length} (${ivs.filter((i) => i.status === "complete").length} complete, ${ivs.filter((i) => i.synthetic).length} synthetic)`, "",
    "## Interview guide", "", ...getQuestions(id).map((q) => `${q.position}. ${q.text}`), "");
  if (!m) {
    L.push("## Buyer model", "", "_No buyer model yet. Run Synthesize._", "");
  } else {
    L.push("## Summary", "", m.summary, "", "## Themes", "");
    for (const t of m.themes) {
      L.push(`### ${t.title}`, "", t.description, "");
      for (const e of t.evidence) L.push(`> "${e.quote}" [int:${e.interview_id}]`, "");
    }
    L.push("## Objections", "", ...m.objections.map((o) => `- ${o}`), "", "## Jobs to be done", "", ...m.jobs_to_be_done.map((o) => `- ${o}`), "",
      "## Segments", "", ...m.segments.map((x) => `- **${x.name}** (${x.share_estimate}): ${x.description}`), "",
      "## Recommended messages", "", ...m.recommended_messages.map((o) => `- ${o}`), "");
  }
  L.push("---", "_Generated by Gatherlite._", "");
  const slug = s.title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "study";
  return new Response(L.join("\n"), {
    headers: { "content-type": "text/markdown; charset=utf-8", "content-disposition": `attachment; filename="${slug}-report.md"` },
  });
}
